#!/usr/bin/env bash
# Builds gd01 for PS Vita inside WSL (VitaSDK from tools/setup-vitasdk.sh).
# Output: $OUT/gd01.vpk (copied to build-out/ in the repo when it exists).
#
# Usage (from PowerShell):
#   wsl -d Ubuntu -u root -- bash /mnt/d/Personal/guitar-hero-vita/tools/build-vita.sh [extra ninja args, e.g. -k 0]
set -euo pipefail

export VITASDK="${VITASDK:-/usr/local/vitasdk}"
export PATH="$VITASDK/bin:$PATH"
REPO="$(cd "$(dirname "$0")/.." && pwd)"
OUT="${OUT:-/root/build/gd01-vita}"
DESKTOP="${DESKTOP:-/root/build/gd01-linux}"

# Our upstream patches (patches/), idempotent.
bash "$REPO/tools/apply-patches.sh"

# SPIR-V headers: generated by the desktop build's host glslang, identical on
# every platform. Build the desktop reference first (tools/build-desktop.sh).
mkdir -p "$OUT/gen"
for h in core_renderer_spirv.h core_post_fx_hdr_spirv.h; do
    src="$(find "$DESKTOP" -name "$h" -print -quit)"
    [ -n "$src" ] || { echo "missing $h: run tools/build-desktop.sh first" >&2; exit 1; }
    cp -u "$src" "$OUT/gen/"
done

# Our vitaGL build (tools/build-vitagl.sh) when it exists; VITAGL_DIR= (empty)
# links the SDK's.
VITAGL_DIR="${VITAGL_DIR-/root/build/vitagl}"
[ -f "$VITAGL_DIR/libvitaGL.a" ] || VITAGL_DIR=""

cmake -S "$REPO/vita" -B "$OUT" -G Ninja \
    -DCMAKE_TOOLCHAIN_FILE="$VITASDK/share/vita.toolchain.cmake" \
    -DCMAKE_BUILD_TYPE=Release \
    -DGD01_VITAGL_DIR="$VITAGL_DIR"
cmake --build "$OUT" -- "$@"

if [ -f "$OUT/gd01.vpk" ]; then
    mkdir -p "$REPO/build-out"
    cp "$OUT/gd01.vpk" "$REPO/build-out/"
    ls -la "$REPO/build-out/gd01.vpk"
fi
